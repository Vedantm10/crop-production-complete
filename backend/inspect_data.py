import pandas as pd
import numpy as np

df = pd.read_csv('data/crop_production_1997_2025.csv')
print('=== SHAPE ===')
print(df.shape)
print()
print('=== COLUMNS & DTYPES ===')
print(df.dtypes)
print()
print('=== FIRST 5 ROWS ===')
print(df.head())
print()
print('=== MISSING VALUES ===')
print(df.isnull().sum())
print()
print('=== UNIQUE VALUES PER COLUMN ===')
for col in df.columns:
    print(col + ': ' + str(df[col].nunique()) + ' unique values')
print()
print('=== DATA_TYPE COLUMN UNIQUE VALUES ===')
print(df['Data_Type'].value_counts())
print()
print('=== CROP_YEAR RANGE ===')
print('Min year: ' + str(df['Crop_Year'].min()) + ', Max year: ' + str(df['Crop_Year'].max()))
print('Unique years: ' + str(sorted(df['Crop_Year'].unique())))
print()
print('=== STATES ===')
print(sorted(df['State_Name'].unique()))
print()
print('=== SEASONS ===')
print(df['Season'].value_counts())
print()
print('=== TOP 20 CROPS ===')
print(df['Crop'].value_counts().head(20))
print()
print('=== DATA_TYPE BY YEAR (recent years) ===')
recent = df[df['Crop_Year'] >= 2018]
print(recent.groupby(['Crop_Year', 'Data_Type']).size().reset_index(name='count'))
print()
print('=== PRODUCTION STATS ===')
print(df['Production'].describe())
print()
print('=== AREA STATS ===')
print(df['Area'].describe())
print()
print('=== NEGATIVE OR ZERO VALUES ===')
print('Negative Production: ' + str((df['Production'] < 0).sum()))
print('Zero Production: ' + str((df['Production'] == 0).sum()))
print('Negative Area: ' + str((df['Area'] < 0).sum()))
print('Zero Area: ' + str((df['Area'] == 0).sum()))
print()
print('=== DUPLICATES ===')
print('Total duplicate rows: ' + str(df.duplicated().sum()))
print('Duplicate on key cols: ' + str(df.duplicated(subset=['State_Name','District_Name','Crop_Year','Season','Crop']).sum()))
print()
print('=== SAMPLE STATE NAMES ===')
states = sorted(df['State_Name'].unique())
for s in states:
    print(repr(s))
print()
print('=== SAMPLE DISTRICT NAMES (first 20) ===')
print(sorted(df['District_Name'].unique())[:20])
print()
print('=== MISSING PRODUCTION SAMPLES ===')
missing_prod = df[df['Production'].isnull()]
print('Rows with missing Production: ' + str(len(missing_prod)))
print(missing_prod[['State_Name','District_Name','Crop_Year','Season','Crop','Area','Production','Data_Type']].head(10))
print()
print('=== YEAR COVERAGE BY DATA TYPE ===')
for year in sorted(df['Crop_Year'].unique()):
    yr_data = df[df['Crop_Year'] == year]
    types = yr_data['Data_Type'].value_counts().to_dict()
    print('Year ' + str(year) + ': ' + str(types))
